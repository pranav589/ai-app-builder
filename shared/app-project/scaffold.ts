import type { FileMap } from "@app/shared/verify/types"

export const BABEL_CONFIG = `module.exports = function (api) {
  api.cache(true)
  return { presets: ["babel-preset-expo"] }
}
`

export const metroConfigGeneric = () => `const { getDefaultConfig } = require("expo/metro-config")
module.exports = getDefaultConfig(__dirname)
`

export const metroConfigForDevice = (projectId: string) => `const { getDefaultConfig } = require("expo/metro-config")
const config = getDefaultConfig(__dirname)
config.cacheVersion = ${JSON.stringify(projectId)}
module.exports = config
`

export const GITIGNORE = "node_modules/\n.expo/\ndist/\nweb-build/\n*.log\n.env\n"

/** `extra` is appended after the getting-started steps (the backend provider's section for a connected app). */
export function readmeFile(projectName: string, extra = ""): string {
  return `# ${projectName}

This is an [Expo](https://expo.dev) project generated by Anything.

## Getting started

1. Install dependencies:
   \`\`\`bash
   npm install
   \`\`\`

2. Start the development server:
   \`\`\`bash
   npx expo start
   \`\`\`

3. Open the app:
   - Scan the QR code from Expo Go (Android) or the Camera app (iOS)
   - Press \`a\` for Android emulator
   - Press \`i\` for iOS simulator
   - Press \`w\` for web
${extra}`
}

export function slug(s: string): string {
  return s.toLowerCase().replace(/[^a-z0-9]+/g, "-").replace(/^-|-$/g, "") || "my-app"
}

export function scaffoldFiles(projectId: string | null): FileMap {
  return {
    "babel.config.js": BABEL_CONFIG,
    "metro.config.js": projectId ? metroConfigForDevice(projectId) : metroConfigGeneric(),
    ".gitignore": GITIGNORE,
  }
}
