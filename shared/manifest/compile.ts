// Manifest -> compiler-owned files (Section 3 ownership table: app/_layout.tsx,
// app/(tabs)/_layout.tsx, app/index.tsx, lib/nav.ts, data/types.ts). Pure and
// deterministic: sorted keys, no timestamps, no random ids, so the same
// manifest always produces byte-identical output (see the determinism test).
//
// Adapted from poc/verified-code/src/compiler/compile.ts to this app's real
// shape: Expo Router file-based screens (not a manual ROUTES map), native
// tabs with icons from the icon vocabulary (lib/app-project/icons.ts)
// instead of a manifest-local theme/entity system, and typed navigation
// that wraps the real expo-router APIs (lib/nav.ts) rather than a custom
// nav runtime, so app code written against it runs unchanged on-device.

import { ICONS } from "@app/shared/app-project/icons"
import { screenHref } from "@app/shared/app-project/project"
import { generateDataTypes, type DataModel } from "@app/shared/app-runtime/data-model"
import type { FileMap } from "@app/shared/verify/types"
import type { AppManifest, ManifestScreen } from "./schema"

export const GENERATED_HEADER = "// @generated by the manifest compiler (lib/manifest/compile.ts). Do not edit: change the manifest instead.\n"

const sortedEntries = <T>(o: Record<string, T>) => Object.entries(o).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
const tsParamType = (t: "string" | "number") => t

function iconOf(screen: ManifestScreen) {
  return ICONS.find((i) => i.ion === screen.icon) ?? ICONS[0]
}

// ---------------------------------------------------------------- lib/nav.ts

function navFile(m: AppManifest): string {
  const ids = Object.keys(m.screens).sort()
  const paramsType = ids
    .map((id) => {
      const p = sortedEntries(m.screens[id].params ?? {})
      if (!p.length) return `  ${JSON.stringify(id)}: undefined`
      const body = p.map(([k, t]) => `${JSON.stringify(k)}: ${tsParamType(t)}`).join("; ")
      return `  ${JSON.stringify(id)}: { ${body} }`
    })
    .join("\n")
  const hrefs = ids.map((id) => `  ${JSON.stringify(id)}: ${JSON.stringify(screenHref({ id }))},`).join("\n")

  return `${GENERATED_HEADER}import { router, useLocalSearchParams, type Href } from "expo-router"

/** Every screen in the manifest and the params it is opened with. */
export type ScreenParams = {
${paramsType}
}
export type ScreenId = keyof ScreenParams

const HREF: Record<ScreenId, string> = {
${hrefs}
}

/** One tuple per screen: [screen] or [screen, params]. A wrong screen id or missing params is a type error. */
type GoArgs = { [S in ScreenId]: ScreenParams[S] extends undefined ? [screen: S] : [screen: S, params: NonNullable<ScreenParams[S]>] }[ScreenId]

/** go("habit-detail", { id }) navigates by screen id, not a string path; params are typed per screen. */
export function go(...args: GoArgs): void {
  const [screen, params] = args
  router.push((params ? { pathname: HREF[screen], params } : HREF[screen]) as Href)
}

export const back = () => router.back()

/** useParams("habit-detail") reads this screen's own params, typed from the manifest. */
export function useParams<S extends ScreenId>(_screen: S): ScreenParams[S] extends undefined ? Record<string, never> : NonNullable<ScreenParams[S]> {
  return useLocalSearchParams() as never
}
`
}

// ---------------------------------------------------------------- app/_layout.tsx, app/(tabs)/_layout.tsx, app/index.tsx

function rootLayoutFile(m: AppManifest, connected: boolean): string {
  const modals = Object.keys(m.screens)
    .filter((id) => m.screens[id].presentation === "modal")
    .sort()
  const stack = `<Stack screenOptions={{ headerShown: false }}>
${modals.map((id) => `            <Stack.Screen name="${id}" options={{ presentation: "modal" }} />`).join("\n")}
          </Stack>`
  // GestureHandlerRootView: on a device, gesture-handler only recognizes
  // gestures (@/motion's SwipeRow and Sheet, app code's usePanGesture) under
  // one, and a production bundle ignores them silently without it.
  // QueryClientProvider only once a backend is connected: that's the only
  // time any screen uses React Query (lib/api.ts, written by the
  // backend-conversion step alongside the connected screens themselves).
  return `${GENERATED_HEADER}import { Stack } from "expo-router"
import { GestureHandlerRootView } from "react-native-gesture-handler"
import { SafeAreaProvider } from "react-native-safe-area-context"
import { ThemeProvider } from "@/theme"
${connected ? `import { QueryClientProvider } from "@tanstack/react-query"\nimport { queryClient } from "@/lib/api"\n` : ""}
export default function RootLayout() {
  return (
    <GestureHandlerRootView style={{ flex: 1 }}>
      <ThemeProvider>
        <SafeAreaProvider>
          ${connected ? `<QueryClientProvider client={queryClient}>\n          ${stack}\n          </QueryClientProvider>` : stack}
        </SafeAreaProvider>
      </ThemeProvider>
    </GestureHandlerRootView>
  )
}
`
}

function tabsLayoutFile(m: AppManifest): string {
  return `${GENERATED_HEADER}import { NativeTabs } from "expo-router/native-tabs"
import { useTheme } from "@/theme"

export default function TabsLayout() {
  const t = useTheme()
  return (
    <NativeTabs tintColor={t.colors.primary}>
${m.navigation.tabs
  .map((id) => {
    const i = iconOf(m.screens[id])
    return `      <NativeTabs.Trigger name="${id}">
        <NativeTabs.Trigger.Label>${m.screens[id].title.replace(/[<>{}]/g, "")}</NativeTabs.Trigger.Label>
        <NativeTabs.Trigger.Icon sf={{ default: "${i.sf}", selected: "${i.sfSelected}" }} md="${i.md}" />
      </NativeTabs.Trigger>`
  })
  .join("\n")}
    </NativeTabs>
  )
}
`
}

function indexFile(m: AppManifest): string {
  const href = screenHref({ id: m.navigation.initial })
  return `${GENERATED_HEADER}import { Redirect } from "expo-router"

// The app opens on its first screen.
export default function Index() {
  return <Redirect href="${href}" />
}
`
}

// ---------------------------------------------------------------- data/types.ts

function toDataModel(m: AppManifest): DataModel {
  return {
    hash: "",
    settings: {},
    user: { name: "", email: "" },
    collections: sortedEntries(m.collections).map(([name, c]) => ({
      name,
      label: c.label,
      fields: sortedEntries(c.fields).map(([fname, f]) => ({ name: fname, type: f.type, label: f.label, options: f.options })),
      seed: c.seed,
    })),
  }
}

// ---------------------------------------------------------------- entry point

/** Paths this compiler writes; nothing else may write them (lib/verify/ownership.ts). */
export const COMPILER_PATHS = ["app/_layout.tsx", "app/(tabs)/_layout.tsx", "app/index.tsx", "lib/nav.ts", "data/types.ts"]

export function compileManifest(m: AppManifest, opts: { connected?: boolean } = {}): FileMap {
  const out: FileMap = {
    "app/_layout.tsx": rootLayoutFile(m, !!opts.connected),
    "app/index.tsx": indexFile(m),
    "lib/nav.ts": navFile(m),
    "data/types.ts": generateDataTypes(toDataModel(m)),
  }
  if (m.navigation.tabs.length) out["app/(tabs)/_layout.tsx"] = tabsLayoutFile(m)
  return out
}
