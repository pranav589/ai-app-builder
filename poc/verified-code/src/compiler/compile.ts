import type { AppManifest } from "../core/manifest"
import type { FileMap } from "../core/types"

// Manifest -> compiler-owned files. Deterministic: sorted keys, no timestamps,
// no random ids, so the same manifest always gives byte-identical output.

export const GENERATED_HEADER = "// @generated by the manifest compiler. Do not edit: change the manifest instead.\n"

const sortedEntries = <T>(o: Record<string, T>) => Object.entries(o).sort(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0))
const pascal = (s: string) => s[0].toUpperCase() + s.slice(1)

export function plural(name: string) {
  if (/[^aeiou]y$/i.test(name)) return name.slice(0, -1) + "ies"
  if (/(s|x|z|ch|sh)$/i.test(name)) return name + "es"
  return name + "s"
}

function tsFieldType(t: string): string {
  const base = t.replace(/\?$/, "")
  if (base === "string" || base === "date" || base.startsWith("ref:")) return "string"
  if (base === "int" || base === "number") return "number"
  if (base === "bool") return "boolean"
  throw new Error(`unknown field type ${t}`)
}

function tsParamType(t: string) {
  return t === "number" ? "number" : "string"
}

const RADIUS = {
  sharp: { sm: 2, md: 4, lg: 6, pill: 999 },
  soft: { sm: 6, md: 10, lg: 16, pill: 999 },
  round: { sm: 10, md: 16, lg: 24, pill: 999 },
}

function navFile(m: AppManifest) {
  const params = sortedEntries(m.screens)
    .map(([id, s]) => {
      const p = sortedEntries(s.params ?? {})
      if (!p.length) return `  ${id}: undefined`
      const body = p
        .map(([k, t]) => {
          const ref = /^ref:(.+)$/.exec(t)?.[1]
          return `${k}: ${tsParamType(t)}${ref ? ` /* id of ${ref} */` : ""}`
        })
        .join("; ")
      return `  ${id}: { ${body} }`
    })
    .join("\n")
  const meta = sortedEntries(m.screens)
    .map(([id, s]) => `  ${id}: { title: ${JSON.stringify(s.title)}, presentation: ${JSON.stringify(s.presentation)} },`)
    .join("\n")
  return `${GENERATED_HEADER}import { createNav } from "@app/nav-runtime"
import type { ScreenMeta } from "@app/shell"

/** Every screen in the app and the params it is opened with. */
export type ScreenParams = {
${params}
}
export type ScreenId = keyof ScreenParams

/** const nav = useNav(); nav.go("screenId", params?); nav.back() — useParams("screenId") reads the current params. */
export const { useNav, useParams } = createNav<ScreenParams>()

export const SCREENS: Record<ScreenId, ScreenMeta> = {
${meta}
}
export const TABS = ${JSON.stringify(m.navigation.tabs)} as const satisfies readonly ScreenId[]
export const INITIAL: ScreenId = ${JSON.stringify(m.navigation.initial)}
`
}

function dataFile(m: AppManifest) {
  const parts: string[] = [
    `${GENERATED_HEADER}import { useCollection, useRecord, type CollectionApi, type QueryOptions, type RecordApi } from "@app/data-runtime"\n`,
  ]
  for (const [name, e] of sortedEntries(m.entities)) {
    const fields = sortedEntries(e.fields)
      .map(([f, t]) => {
        const ref = /^ref:([A-Za-z0-9]+)/.exec(t)?.[1]
        return `  ${f}${t.endsWith("?") ? "?" : ""}: ${tsFieldType(t)}${ref ? ` // id of ${ref}` : t.startsWith("date") ? " // ISO date, e.g. 2026-03-01" : ""}`
      })
      .join("\n")
    const many = plural(name)
    parts.push(`export type ${name} = {
  id: string
  createdAt: string
${fields}
}
/** List ${many}: { data, add, update, remove }. */
export const use${many} = (opts?: QueryOptions<${name}>): CollectionApi<${name}> => useCollection<${name}>(${JSON.stringify(name)}, opts)
/** One ${name} by id: { data (null when missing), update, remove }. */
export const use${name} = (id: string | undefined): RecordApi<${name}> => useRecord<${name}>(${JSON.stringify(name)}, id)
`)
  }
  const seed = Object.fromEntries(sortedEntries(m.entities).map(([n, e]) => [n, e.seed]))
  parts.push(`export const SEED: Record<string, Record<string, unknown>[]> = ${JSON.stringify(seed, null, 2)}\n`)
  return parts.join("\n")
}

function themeFile(m: AppManifest) {
  const theme = {
    mode: m.theme.mode,
    colors: Object.fromEntries(sortedEntries(m.theme.colors)),
    space: { none: 0, xs: 4, sm: 8, md: 12, lg: 16, xl: 24 },
    radius: RADIUS[m.theme.radius],
  }
  return `${GENERATED_HEADER}import type { Theme } from "@app/theme"

export const THEME: Theme = ${JSON.stringify(theme, null, 2)}
`
}

function routesFile(m: AppManifest) {
  const ids = Object.keys(m.screens).sort()
  const imports = ids.map((id) => `import ${pascal(id)}Screen from "@/screens/${id}"`).join("\n")
  const entries = ids.map((id) => `  ${id}: ${pascal(id)}Screen,`).join("\n")
  return `${GENERATED_HEADER}import type * as React from "react"
import { AppShell } from "@app/shell"
import { SCREENS, TABS, type ScreenId } from "@/nav"
${imports}

// Every screen in the manifest must have a file at screens/<id>.tsx whose default
// export is a component without props. A missing file is a type error here.
export const ROUTES: Record<ScreenId, React.ComponentType> = {
${entries}
}

export default function App() {
  return <AppShell routes={ROUTES} meta={SCREENS} tabs={TABS} />
}
`
}

export const COMPILER_PATHS = ["nav/index.ts", "data/index.ts", "theme/index.ts", "app/routes.tsx"]

export function compileManifest(m: AppManifest): FileMap {
  return {
    "app/routes.tsx": routesFile(m),
    "data/index.ts": dataFile(m),
    "nav/index.ts": navFile(m),
    "theme/index.ts": themeFile(m),
  }
}
